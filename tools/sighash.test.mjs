// tools/sighash.test.mjs — the message a signature is over, against the
// vectors consensus itself is tested with.
//
//   node --test tools/sighash.test.mjs
//
// The spend rung claims ∇ s p ( ⌘ w ) and points a reader at the bytes behind
// ⌘. That is a promise the page can only keep if the serialization is right to
// the byte, and a preimage that is subtly wrong is worse than none at all: it
// would put math on a page whose whole claim is that the math can be checked,
// and a reader who tried to check it would conclude the chain was wrong rather
// than the book.
//
// So nothing here is reasoned about. The legacy digest is run against all 500
// cases in Bitcoin Core's own src/test/data/sighash.json — generated by the
// implementation consensus actually runs, and covering the shapes nobody would
// think to write down: SINGLE past the end of the outputs, an input index past
// the end, OP_CODESEPARATOR inside a scriptCode. BIP143 is run against the
// worked examples in the BIP, which print their preimages in full, including
// all six sighash flags over one input.

import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

import { parseTx, legacyPreimage, bip143Preimage, dsha256, compact,
         sighashOf, sighashName, v0KeyHashCode } from '../web/btc-sighash.js';

// Core writes a uint256 the way it prints one, which is backwards from the way
// it hashes one.
const reversed = (h) => (h.match(/../g) || []).reverse().join('');
// The two consensus bugs the legacy algorithm keeps rather than fixes: both
// digest as the number 1, and legacyPreimage returns null instead of inventing
// a serialization that was never hashed.
const ONE = reversed('01' + '00'.repeat(31));

test('the legacy digest matches Core on all 500 of its own vectors', async () => {
  const rows = JSON.parse(await readFile(new URL('./fixtures-sighash.json', import.meta.url), 'utf8'))
    .slice(1);   // the first row is the column legend
  assert.equal(rows.length, 500, 'the fixture lost or gained cases');
  for (const [raw, script, index, type, expected] of rows) {
    const preimage = legacyPreimage(parseTx(raw), index, script, type | 0);
    if (preimage === null) { assert.equal(expected, ONE, `${raw.slice(0, 16)}… is not the 1 case`); continue; }
    assert.equal(reversed(await dsha256(preimage)), expected,
      `index ${index}, type ${type}, tx ${raw.slice(0, 24)}…`);
  }
});

test('the two shapes that were never serialized are refused, not invented', () => {
  // Core's own vectors are generated from valid combinations and never reach
  // these, so they are built here. Both digest as the number 1 in consensus --
  // not because anything was hashed, but because an early return handed back a
  // uint256 and the bug is now the rule. A page that printed a preimage for
  // either would be showing bytes nobody ever hashed.
  const input = (txid, n) => `${txid.repeat(32)}0${n}000000` + '00' + 'ffffffff';
  const twoInOneOut = `01000000` + '02' + input('11', 0) + input('22', 1)
    + '01' + '0000000000000000' + '00' + '00000000';
  const tx = parseTx(twoInOneOut);
  assert.equal(tx.ins.length, 2);
  assert.equal(tx.outs.length, 1);
  // An input index past the end of the inputs.
  assert.equal(legacyPreimage(tx, 2, '51', 0x01), null);
  // …and SIGHASH_SINGLE naming an output that is not there.
  assert.equal(legacyPreimage(tx, 1, '51', 0x03), null);
  assert.ok(legacyPreimage(tx, 1, '51', 0x01), 'the same index under ALL is ordinary');
  assert.ok(legacyPreimage(tx, 0, '51', 0x03), 'and SINGLE at an index that has an output');
});


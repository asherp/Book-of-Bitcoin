test('BIP143 writes the preimages the BIP prints', async () => {
  for (const v of [NATIVE_P2WPKH, P2SH_P2WPKH]) {
    const got = await bip143Preimage(parseTx(v.raw), v.index, v.code, v.value, v.type);
    assert.equal(got, v.preimage, v.what);
    if (v.sighash) assert.equal(await dsha256(got), v.sighash, `${v.what}: the digest`);
  }
  // The amount really is in there, which is the whole reason BIP143 exists: a
  // legacy preimage of the same input commits to no value at all.
  const amount = '0046c32300000000';
  assert.ok(NATIVE_P2WPKH.preimage.includes(amount), 'six bitcoin, eight bytes, little endian');
  const legacy = legacyPreimage(parseTx(NATIVE_P2WPKH.raw), 1, NATIVE_P2WPKH.code, 1);
  assert.ok(!legacy.includes(amount), 'and the algorithm it replaced could not say it');
});

test('every sighash flag zeroes exactly what it frees', async () => {
  const tx = parseTx(SIX_FLAGS.raw);
  for (const [type, expected] of FLAGS) {
    const got = await bip143Preimage(tx, SIX_FLAGS.index, SIX_FLAGS.code, SIX_FLAGS.value, type);
    assert.equal(got, expected, sighashName(type));
  }
  // …and the field each flag lets go is readable off the preimage itself,
  // which is the reason a page sets the preimage rather than the digest.
  const of = (type) => FLAGS.find(([t]) => t === type)[1];
  assert.ok(of(0x02).includes(`${ZERO}0000000002000000`), 'NONE signs no output');
  assert.ok(of(0x81).startsWith(`01000000${ZERO}${ZERO}`), 'ANYONECANPAY signs no other input');
  assert.notEqual(of(0x03).slice(-40), of(0x01).slice(-40), 'SINGLE signs one output, not all');
});

test('a signature carries its own flag, and says which', () => {
  const der = '3044' + '02'.repeat(34) + '01';
  assert.equal(sighashOf(der), 0x01);
  assert.equal(sighashName(sighashOf(der)), 'ALL');
  assert.equal(sighashName(0x83), 'SINGLE|ANYONECANPAY');
  // A 64-byte Schnorr signature writes its flag by leaving it out: the default
  // is ALL, and a byte would only be there to say something else.
  assert.equal(sighashOf('ab'.repeat(64)), 0x00);
  assert.equal(sighashOf('ab'.repeat(64) + '03'), 0x03, 'and 65 bytes is that byte');
});

test('the compact size is Bitcoin’s, not a varint', () => {
  // Every length in both preimages runs through this, so its boundaries are
  // worth pinning: a script of 253 bytes serializes differently from one of 252.
  assert.equal(compact(0), '00');
  assert.equal(compact(252), 'fc');
  assert.equal(compact(253), 'fdfd00');
  assert.equal(compact(0xffff), 'fdffff');
  assert.equal(compact(0x10000), 'fe00000100');
  assert.equal(compact(0xffffffff), 'feffffffff');
  assert.equal(compact(0x100000000), 'ff0000000001000000');
});

test('a transaction is read back exactly as it was written', async () => {
  // The parse has to be lossless over the fields a digest commits to, and the
  // 500-vector run above would catch most drift — but a segwit transaction
  // never appears there, and its marker and flag are exactly what a digest
  // must NOT see.
  const signed = '01000000000102fff7f7881a8099afa6940d42d1e7f6362bec38171ea3edf433541db4e4ad969f'
    + '00000000494830450221008b9d1dc26ba6a9cb62127b02742fa9d754cd3bebf337f7a55d114c8e5cdd30be'
    + '022040529b194ba3f9281a99f2b1c0a19c0489bc22ede944ccf4ecbab4cc618ef3ed01eeffffff'
    + 'ef51e1b804cc89d182d279655c3aa89e815b1b309fe287d9b2b55d57b90ec68a0100000000ffffffff'
    + '02202cb206000000001976a9148280b37df378db99f66f85c95a783a76ac7a6d5988ac'
    + '9093510d000000001976a9143bde42dbee7e4dbe6a21b2d50ce2f0167faa815988ac0002'
    + '47304402203609e17b84f6a7d30c80bfa610b5b4542f32a8a0d5447a12fb1366d7f01cc44a'
    + '0220573a954c4518331561406f90300e8f3358f51928d43c212a8caed02de67eebee01'
    + '21025476c2e83188368da1ff3e292e7acafcdb3566bb0ad253f62fc70f07aeee635711000000';
  const tx = parseTx(signed);
  assert.equal(tx.segwit, true);
  assert.equal(tx.ins.length, 2);
  assert.equal(tx.outs.length, 2);
  assert.equal(tx.locktime, '11000000');
  assert.deepEqual(tx.ins[1].witness.length, 2, 'the witness is read, and then not signed over');
  // The digest over the SIGNED transaction is the one the BIP prints for the
  // unsigned one: a witness changes nothing a signature covers, which is what
  // segregating it means.
  const got = await bip143Preimage(tx, 1, NATIVE_P2WPKH.code, NATIVE_P2WPKH.value, 1);
  assert.equal(got, NATIVE_P2WPKH.preimage);
});

test('the algorithm is chosen by the output, not by the spend', async () => {
  const { messageOf } = await import('../web/btc-sighash.js');
  const signed = '01000000000102fff7f7881a8099afa6940d42d1e7f6362bec38171ea3edf433541db4e4ad969f'
    + '00000000494830450221008b9d1dc26ba6a9cb62127b02742fa9d754cd3bebf337f7a55d114c8e5cdd30be'
    + '022040529b194ba3f9281a99f2b1c0a19c0489bc22ede944ccf4ecbab4cc618ef3ed01eeffffff'
    + 'ef51e1b804cc89d182d279655c3aa89e815b1b309fe287d9b2b55d57b90ec68a0100000000ffffffff'
    + '02202cb206000000001976a9148280b37df378db99f66f85c95a783a76ac7a6d5988ac'
    + '9093510d000000001976a9143bde42dbee7e4dbe6a21b2d50ce2f0167faa815988ac0002'
    + '47304402203609e17b84f6a7d30c80bfa610b5b4542f32a8a0d5447a12fb1366d7f01cc44a'
    + '0220573a954c4518331561406f90300e8f3358f51928d43c212a8caed02de67eebee01'
    + '21025476c2e83188368da1ff3e292e7acafcdb3566bb0ad253f62fc70f07aeee635711000000';
  // Input 1 opened a v0 key-hash output, so it signed under BIP143 — and the
  // scriptCode is derived from the program's own datum, never read off the
  // spend. The witness and the sighash flag come off the input itself.
  const v0 = await messageOf({ script: '00141d0f172a0ecb48aee1be1f2687d2963ae33f71a1',
    raw: signed, index: 1, value: 600000000 });
  assert.equal(v0.algorithm, 'BIP143');
  assert.equal(v0.type, 0x01);
  assert.equal(v0.scriptCode, v0KeyHashCode('1d0f172a0ecb48aee1be1f2687d2963ae33f71a1'));
  assert.equal(v0.preimage, NATIVE_P2WPKH.preimage);
  assert.equal(v0.digest, NATIVE_P2WPKH.sighash);
  // Input 0 of the very same transaction opened a P2PK output, so it signed
  // under the legacy digest. One transaction, two algorithms — which is why the
  // choice is made from the output and not from the spend.
  const legacy = await messageOf({ script: '2103c9f4836b9a4f77fc0d81f7bcb01b7f1b35916864b9476c241ce9fc198bd25432ac',
    raw: signed, index: 0, value: 625000000,
    scriptsig: '4830450221008b9d1dc26ba6a9cb62127b02742fa9d754cd3bebf337f7a55d114c8e5cdd30be'
      + '022040529b194ba3f9281a99f2b1c0a19c0489bc22ede944ccf4ecbab4cc618ef3ed01' });
  assert.equal(legacy.algorithm, 'legacy');
  assert.equal(legacy.type, 0x01);
  assert.equal(legacy.preimage,
    legacyPreimage(parseTx(signed), 0, '2103c9f4836b9a4f77fc0d81f7bcb01b7f1b35916864b9476c241ce9fc198bd25432ac', 1));
  // …and the amount is in one and not the other, which the fields say in words.
  assert.ok(v0.fields.some(([name]) => name === 'amount'));
  assert.ok(legacy.fields.some(([name]) => name === '(no amount)'));

  // Taproot's digest is BIP341's and is not written here, so it is not claimed.
  assert.equal(await messageOf({ script: '5120' + 'ab'.repeat(32), raw: signed, index: 1, value: 1 }), null,
    'a message this cannot serialize is named as unknown, not guessed');
  // BIP143 signs the amount, so without one there is no message to write.
  assert.equal(await messageOf({ script: '00141d0f172a0ecb48aee1be1f2687d2963ae33f71a1',
    raw: signed, index: 1, value: null }), null);
});

test('a real signature verifies against the preimage this writes', async () => {
  // The end of the argument. Every test above compares bytes against bytes
  // somebody else wrote down; this one asks secp256k1. If the serialization
  // were wrong in any field, in any byte, the digest would be a different
  // number and this would fail — which is the same check a node performs, and
  // the same one a reader with the footnote in front of them can perform.
  const crypto = await import('node:crypto');
  const preimage = await bip143Preimage(parseTx(NATIVE_P2WPKH.raw), NATIVE_P2WPKH.index,
    NATIVE_P2WPKH.code, NATIVE_P2WPKH.value, NATIVE_P2WPKH.type);
  // The key and the signature are the BIP's, printed beside the transaction.
  const pubkey = '025476c2e83188368da1ff3e292e7acafcdb3566bb0ad253f62fc70f07aeee6357';
  const sig = '304402203609e17b84f6a7d30c80bfa610b5b4542f32a8a0d5447a12fb1366d7f01cc44a'
    + '0220573a954c4518331561406f90300e8f3358f51928d43c212a8caed02de67eebee';
  // A compressed point, wrapped in the SPKI the platform wants: the algorithm
  // is ecPublicKey over secp256k1, and the point follows.
  const spki = Buffer.concat([Buffer.from('3036301006072a8648ce3d020106052b8104000a032200', 'hex'),
    Buffer.from(pubkey, 'hex')]);
  const key = crypto.createPublicKey({ key: spki, format: 'der', type: 'spki' });
  // Bitcoin signs the double hash, so one SHA-256 is taken here and the verifier
  // takes the other — which is what "ECDSA over dSHA256" means when a library
  // only offers you the outer one.
  const once = crypto.createHash('sha256').update(Buffer.from(preimage, 'hex')).digest();
  assert.equal(crypto.verify('sha256', once, key, Buffer.from(sig, 'hex')), true,
    'the signature does not verify — the preimage is wrong somewhere');
  // …and it is not verifying just anything: one byte moved, and it fails.
  const bent = preimage.slice(0, 8) + (preimage[8] === '0' ? '1' : '0') + preimage.slice(9);
  const bentOnce = crypto.createHash('sha256').update(Buffer.from(bent, 'hex')).digest();
  assert.equal(crypto.verify('sha256', bentOnce, key, Buffer.from(sig, 'hex')), false);
});

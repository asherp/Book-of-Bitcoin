//
// btc-sighash.js — the message a signature is over, serialized so a reader can
// hash it themselves.
//
// A spend rung says ∇ s p ( ⌘ ※ ): this signature, under this key, over this
// message. The first two are on the page already — they are what the input
// carried, quoted and cited. The third was a mark with nothing behind it, and
// a demand nobody can evaluate is a demand nobody can check. This module is
// what puts something behind it.
//
// What it produces is the PREIMAGE, not the digest: the bytes that go into the
// hash, in order, with every field nameable. The digest is one dSHA256 away and
// this module will take it, but the preimage is the thing worth setting on a
// page — a reader who has it can hash it in one line and compare, and a reader
// who reads it can see exactly what a signature does and does not commit to.
// The digest alone would only be a number to be believed.
//
// Three algorithms, because Bitcoin has had three, and the difference between
// them is visible in the shape of what comes out:
//
//   legacy   the whole transaction, with every scriptSig blanked but the one
//            being signed, that one replaced by the scriptCode — so the amount
//            being spent is nowhere in it, which is the hole BIP143 was written
//            to close
//   BIP143   fixed fields and three sub-hashes, the input's own value among
//            them, so a signer who is told a value and lied to signs nothing
//            that verifies
//   BIP341   taproot: fixed fields again, but now over every coin the
//            transaction spends — each amount and each locking script, not just
//            this input's — and hashed once under a tagged SHA-256 rather than
//            twice, so no digest of one epoch can be replayed as another's
//
// All three are checked against published vectors rather than reasoned about:
// Core's own sighash.json (500 legacy cases, generated by the implementation
// consensus actually runs), BIP143's worked examples, which print their
// preimages in full, and BIP341's wallet test vectors, which print theirs for
// all seven key-path sighash types. See tools/sighash.test.mjs. Nothing here is
// trusted because it looks right — a preimage that is subtly wrong would put
// false math on a page whose whole claim is that the math can be checked.

// ─── bytes ───────────────────────────────────────────────────────────────

const hex = (bytes) => bytes.map((b) => b.toString(16).padStart(2, '0')).join('');
const bytesOf = (h) => (String(h).match(/../g) || []).map((b) => parseInt(b, 16));

// Little-endian integers, which is how every count and amount rides on the
// wire. BigInt for the 8-byte ones: a satoshi amount passes 2^53 at 90,000 BTC,
// and this is a book about exact numbers.
const le = (n, width) => {
  let v = BigInt(n), out = '';
  for (let i = 0; i < width; i++) { out += Number(v & 0xffn).toString(16).padStart(2, '0'); v >>= 8n; }
  return out;
};

// Bitcoin's compact size, which is not a varint anywhere else: one byte under
// 0xfd, then a marker and 2, 4 or 8 little-endian bytes.
export const compact = (n) => {
  const v = Number(n);
  if (v < 0xfd) return le(v, 1);
  if (v <= 0xffff) return 'fd' + le(v, 2);
  if (v <= 0xffffffff) return 'fe' + le(v, 4);
  return 'ff' + le(v, 8);
};

// A script as it is serialized inside a CTxOut: its length, then its bytes.
const withLength = (script) => compact(script.length / 2) + script;

// The one hash Bitcoin means when it says "hash": SHA-256, twice. WebCrypto is
// async and there is no synchronous digest in a browser, so everything above
// this line is a string and everything that hashes is a promise.
export async function dsha256(h) {
  const once = await crypto.subtle.digest('SHA-256', new Uint8Array(bytesOf(h)));
  const twice = await crypto.subtle.digest('SHA-256', once);
  return hex([...new Uint8Array(twice)]);
}

// …and the one taproot means, which is SHA-256 once. BIP340 through 342 hash
// once and disambiguate by tag instead of by repetition, and the sub-hashes
// inside a BIP341 preimage are bare single hashes.
export async function sha256(h) {
  const once = await crypto.subtle.digest('SHA-256', new Uint8Array(bytesOf(h)));
  return hex([...new Uint8Array(once)]);
}

// A BIP340 tagged hash: SHA-256 over the tag's own hash twice and then the
// message, so a digest taken for one purpose can never verify as a digest
// taken for another. The tag is ASCII, and hashing it twice pads the prefix to
// 64 bytes — one whole SHA-256 block, which lets an implementation precompute
// it; this one just takes it.
export async function taggedHash(tag, h) {
  const t = await sha256(hex([...new TextEncoder().encode(tag)]));
  return sha256(t + t + h);
}

// ─── reading a transaction off the wire ──────────────────────────────────
//
// Enough of one to sign over: the fields a digest commits to, in the order it
// commits to them. Segwit's marker and flag are read and dropped — a witness is
// never in either digest, which is the whole of what "segregated" means here.
export function parseTx(raw) {
  const b = bytesOf(raw);
  let i = 0;
  const take = (n) => { const s = hex(b.slice(i, i + n)); i += n; return s; };
  const u32 = () => { const s = take(4); return s; };
  const size = () => {
    const first = b[i++];
    if (first < 0xfd) return first;
    const n = first === 0xfd ? 2 : first === 0xfe ? 4 : 8;
    const s = take(n);
    return Number(BigInt('0x' + (s.match(/../g) || []).reverse().join('')));
  };
  const version = u32();
  let segwit = false;
  if (b[i] === 0x00 && b[i + 1] === 0x01) { segwit = true; i += 2; }
  const ins = [];
  const nIn = size();
  for (let n = 0; n < nIn; n++) {
    const txid = take(32), vout = take(4);
    const script = take(size());
    ins.push({ txid, vout, script, sequence: take(4) });
  }
  const outs = [];
  const nOut = size();
  for (let n = 0; n < nOut; n++) {
    const value = take(8);
    outs.push({ value, script: take(size()) });
  }
  if (segwit) {
    for (let n = 0; n < nIn; n++) {
      const items = [];
      const count = size();
      for (let k = 0; k < count; k++) items.push(take(size()));
      ins[n].witness = items;
    }
  }
  return { version, ins, outs, locktime: take(4), segwit };
}

// ─── sighash flags ───────────────────────────────────────────────────────

export const SIGHASH_ALL = 0x01, SIGHASH_NONE = 0x02, SIGHASH_SINGLE = 0x03;
export const SIGHASH_ANYONECANPAY = 0x80;
const base = (type) => type & 0x1f;
const anyone = (type) => Boolean(type & SIGHASH_ANYONECANPAY);

// What a flag is called, for the page that has to say it. The names are
// consensus's own; the reading beside each is what it costs. 0x00 is BIP341's
// SIGHASH_DEFAULT — ALL, said by leaving the byte off the signature — and it
// only ever arrives here from a 64-byte Schnorr signature, since everywhere
// else a flag is a byte that is present.
export function sighashName(type) {
  if (type === 0x00) return 'DEFAULT (ALL)';
  const names = { [SIGHASH_ALL]: 'ALL', [SIGHASH_NONE]: 'NONE', [SIGHASH_SINGLE]: 'SINGLE' };
  const b = names[base(type)] ?? `0x${base(type).toString(16)}`;
  return anyone(type) ? `${b}|ANYONECANPAY` : b;
}

// The flag a signature carries, which is its last byte — DER for ECDSA, and for
// Schnorr a 65th byte that is only there when the flag is not the default.
export function sighashOf(sig) {
  const n = sig.length / 2;
  if (n === 64) return 0x00;                      // BIP341's default, written by omission
  return parseInt(sig.slice(-2), 16);
}

// ─── the legacy digest ───────────────────────────────────────────────────
//
// Everything before segwit, and still every P2PK, P2PKH, bare multisig and P2SH
// spend. The transaction is serialized again with one input's scriptSig
// replaced by the scriptCode and every other input's blanked, then the sighash
// type is appended as four little-endian bytes and the whole is hashed twice.
//
// The two shapes that are not a serialization at all are consensus's own bugs,
// kept because the chain is full of them: an input index past the end, and
// SIGHASH_SINGLE with no output at that index, both digest as the number 1
// rather than failing. A caller gets null and should say so rather than print a
// preimage that was never hashed.
export function legacyPreimage(tx, nIn, scriptCode, type) {
  if (nIn >= tx.ins.length) return null;
  if (base(type) === SIGHASH_SINGLE && nIn >= tx.outs.length) return null;
  // OP_CODESEPARATOR is struck from the scriptCode wherever it stands. (The
  // FindAndDelete of the signature itself is not done here: it can only matter
  // where a signature was pushed by the scriptCode, which no standard form
  // does, and guessing at it would be worse than declining.)
  const code = (scriptCode.match(/../g) || []).filter((b) => b !== 'ab').join('');
  const one = anyone(type);
  const ins = one ? [tx.ins[nIn]] : tx.ins;
  const body = ins.map((input, k) => {
    const idx = one ? nIn : k;
    const script = idx === nIn ? withLength(code) : compact(0);
    // NONE and SINGLE free every other input's sequence, which is what lets one
    // signer's timelock be rewritten by another's.
    const seq = idx !== nIn && (base(type) === SIGHASH_NONE || base(type) === SIGHASH_SINGLE)
      ? le(0, 4) : input.sequence;
    return input.txid + input.vout + script + seq;
  }).join('');
  const outs = base(type) === SIGHASH_NONE ? []
    : base(type) === SIGHASH_SINGLE ? tx.outs.slice(0, nIn + 1)
    : tx.outs;
  const outBody = outs.map((out, k) => (base(type) === SIGHASH_SINGLE && k !== nIn
    // A blanked output: value −1, and no script. Signed over, and worth
    // nothing to anyone.
    ? 'ffffffffffffffff' + compact(0)
    : out.value + withLength(out.script))).join('');
  return tx.version + compact(ins.length) + body
    + compact(outs.length) + outBody + tx.locktime + le(type, 4);
}

// ─── the BIP143 digest ───────────────────────────────────────────────────
//
// Segwit v0, and the fix that made it worth having: the value being spent is in
// the preimage, so a signer told the wrong amount produces a signature that
// verifies against nothing. The rest of the change is arithmetic — three
// sub-hashes over the inputs and outputs, reusable across every input of a
// transaction, which turns a quadratic verification cost into a linear one.
export async function bip143Preimage(tx, nIn, scriptCode, value, type) {
  const zero = '00'.repeat(32);
  const hashPrevouts = anyone(type) ? zero
    : await dsha256(tx.ins.map((i) => i.txid + i.vout).join(''));
  const hashSequence = anyone(type) || base(type) === SIGHASH_SINGLE || base(type) === SIGHASH_NONE
    ? zero : await dsha256(tx.ins.map((i) => i.sequence).join(''));
  const out = (o) => o.value + withLength(o.script);
  const hashOutputs = base(type) !== SIGHASH_SINGLE && base(type) !== SIGHASH_NONE
    ? await dsha256(tx.outs.map(out).join(''))
    : base(type) === SIGHASH_SINGLE && nIn < tx.outs.length
      ? await dsha256(out(tx.outs[nIn])) : zero;
  const input = tx.ins[nIn];
  return tx.version + hashPrevouts + hashSequence + input.txid + input.vout
    + withLength(scriptCode) + le(value, 8) + input.sequence
    + hashOutputs + tx.locktime + le(type, 4);
}

// The scriptCode a v0 input signs under. For a key-hash program it is the P2PKH
// template consensus builds from the program's own datum — the same script the
// term writes in its ( ) — and for a script-hash program it is the witness
// script the spend revealed.
export const v0KeyHashCode = (h160) => `76a914${h160}88ac`;

// ─── the BIP341 digest ───────────────────────────────────────────────────
//
// Taproot, and BIP143's fix carried to its end: not just this input's value but
// every spent coin's value AND locking script are in the preimage, so a signer
// shown any wrong output — its own or a neighbour's — signs nothing that
// verifies. The sub-hashes are single SHA-256 now, the digest is a TapSighash
// tagged hash taken once, and the whole preimage opens with an epoch byte so
// even the serialization itself is versioned.
//
// The flags also stopped zeroing and started omitting: where BIP143 writes
// thirty-two bytes of zeroes for a field a flag frees, BIP341 leaves the field
// out, which is why two preimages under different flags are different lengths.
// And SIGHASH_SINGLE past the end of the outputs — the shape legacy signing
// digests as the number 1 — is simply invalid here: consensus rejects the
// spend, so there is no preimage to write and null is the truth.
//
// `prevouts` is one {value, script} per input, in input order — the coins this
// transaction spends, which are exactly the thing the chain must be asked for
// because no serialization of the transaction itself carries them.
const BIP341_TYPES = new Set([0x00, 0x01, 0x02, 0x03, 0x81, 0x82, 0x83]);
// SIGHASH_DEFAULT is ALL with the byte left off, so & 3 reads the base right —
// 0 lands with 1 on the ALL side of every branch below.
const single341 = (type) => (type & 3) === SIGHASH_SINGLE;
const none341 = (type) => (type & 3) === SIGHASH_NONE;

// The sub-hashes, kept apart so the fields can be named without hashing twice.
// Under ANYONECANPAY the four input-wide ones are not zeroed but absent, so
// they are simply not set.
async function bip341Parts(tx, nIn, prevouts, type, annex) {
  const out = (o) => o.value + withLength(o.script);
  return {
    ...(anyone(type) ? {} : {
      shaPrevouts: await sha256(tx.ins.map((i) => i.txid + i.vout).join('')),
      shaAmounts: await sha256(prevouts.map((p) => le(p.value, 8)).join('')),
      shaScriptPubkeys: await sha256(prevouts.map((p) => withLength(p.script)).join('')),
      shaSequences: await sha256(tx.ins.map((i) => i.sequence).join('')),
    }),
    shaOutputs: !single341(type) && !none341(type)
      ? await sha256(tx.outs.map(out).join('')) : null,
    shaAnnex: annex ? await sha256(withLength(annex)) : null,
    shaSingle: single341(type) && nIn < tx.outs.length
      ? await sha256(out(tx.outs[nIn])) : null,
  };
}

// The key-path preimage: epoch, flag, and the fields the flag admits, in
// BIP341's own order — the locktime near the head now, the input named by bare
// index, and the annex (when one rides) committed by its hash. The script
// path's extension (the leaf hash, and the position of the last executed
// OP_CODESEPARATOR) is not written here — see messageOf for why it could not
// honestly be.
export async function bip341Preimage(tx, nIn, prevouts, type, { annex = null } = {}) {
  if (nIn >= tx.ins.length || !BIP341_TYPES.has(type)) return null;
  if (single341(type) && nIn >= tx.outs.length) return null;   // invalid, not the number 1
  const one = anyone(type);
  // ANYONECANPAY signs only its own coin, so only that one need be known; every
  // other flag hashes all of them and a single missing coin unmakes the message.
  const spent = Array.isArray(prevouts) && prevouts.length === tx.ins.length ? prevouts : null;
  const need = one ? [spent?.[nIn] ?? prevouts?.[nIn]] : spent;
  if (!need || need.some((p) => !p || p.value == null || !p.script)) return null;
  const p = await bip341Parts(tx, nIn, need, type, annex);
  const input = tx.ins[nIn];
  return '00' + le(type, 1) + tx.version + tx.locktime
    + (one ? '' : p.shaPrevouts + p.shaAmounts + p.shaScriptPubkeys + p.shaSequences)
    + (p.shaOutputs ?? '')
    + le(annex ? 1 : 0, 1)
    + (one ? input.txid + input.vout + le(need[0].value, 8) + withLength(need[0].script) + input.sequence
      : le(nIn, 4))
    + (p.shaAnnex ?? '')
    + (p.shaSingle ?? '');
}

// ─── the fields, named ───────────────────────────────────────────────────
//
// A preimage set as one run of hex is a thing to be believed, not read. What a
// page wants is the same bytes cut at the joints, each piece named — so a
// reader can see that the amount is in there, or that the outputs are not.
//
// Each field carries what it IS as well as what it weighs, because hex is the
// one rendering this book never settles for. `kind` says which reading the
// bytes take and `of` carries the value that reading needs:
//
//   figure     a small integer — a version, a count, an index, a spend type
//   flag       the sighash type, which has a name
//   locktime   a height or a time, and the book has a mark for each
//   sequence   ● ○ † ■n Τd, the same marks the reading sets on an input
//   amount     satoshis, which the book writes in ₿
//   script     bytes that are a script, to be set as opcodes
//   outpoint   a coin: 32 bytes of txid, and which output of it
//   said       high entropy — a hash, and nothing but prose can say it
//   none       no bytes at all (legacy's missing amount)
//
// The split is entropy, and it is the book's own everywhere else: a figure is
// a figure and prints as one, and bytes nobody can read are said in Glossia
// rather than shown as hex. `bytes` stays exactly what it was — the
// serialization, in order — so a page can still join the fields and get the
// preimage back, which is the one claim the footnote exists to support.
const int = (hexLE) => Number(BigInt('0x' + ((hexLE.match(/../g) || ['00']).reverse().join(''))));
const field = (name, bytes, said, kind = 'said', of = null) => ({ name, bytes, said, kind, of });
export function bip143Fields(tx, nIn, scriptCode, value, type, parts) {
  const input = tx.ins[nIn];
  return [
    field('nVersion', tx.version, 'the transaction’s version, four bytes', 'figure', int(tx.version)),
    field('hashPrevouts', parts.hashPrevouts, anyone(type)
      ? 'zero — ANYONECANPAY signs no other input, so any of them may be added or dropped'
      : 'every input’s outpoint, hashed: which coins this transaction spends'),
    field('hashSequence', parts.hashSequence, parts.hashSequence === '00'.repeat(32)
      ? 'zero — this flag leaves every other input’s sequence free to be rewritten'
      : 'every input’s nSequence, hashed'),
    field('outpoint', input.txid + input.vout,
      'the coin this input spends, named as the chain names it',
      'outpoint', { txid: input.txid, vout: int(input.vout) }),
    field('scriptCode', withLength(scriptCode), 'the script this signature is made under',
      'script', scriptCode),
    field('amount', le(value, 8),
      'what the coin is worth — the field legacy signing had no place for', 'amount', value),
    field('nSequence', input.sequence, 'this input’s own sequence', 'sequence', int(input.sequence)),
    field('hashOutputs', parts.hashOutputs, base(type) === SIGHASH_NONE
      ? 'zero — NONE signs no output at all, so where the value goes is not committed to'
      : base(type) === SIGHASH_SINGLE ? 'the one output at this input’s index, hashed'
      : 'every output, hashed: the amounts and where they go'),
    field('nLockTime', tx.locktime, 'the earliest the transaction may be mined',
      'locktime', int(tx.locktime)),
    field('nHashType', le(type, 4),
      `${sighashName(type)} — which of the above the signature covers`, 'flag', type),
  ];
}

// The BIP341 preimage cut at its joints, in the order the bytes run. What the
// list shows is the omitting: a flag that frees a field removes it from the
// serialization outright, so under NONE there is no sha_outputs row at all
// rather than a row of zeroes, and under ANYONECANPAY the transaction-wide
// sub-hashes give way to this input's own coin written out in full.
function bip341Fields(tx, nIn, prevout, type, annex, parts) {
  const input = tx.ins[nIn];
  const one = anyone(type);
  return [
    field('epoch', '00', 'a version byte for the digest itself, so a future soft fork '
      + 'can serialize differently without any message colliding with this one', 'figure', 0),
    field('hash_type', le(type, 1), `${sighashName(type)} — which fields follow: a freed field is `
      + 'left out of this serialization, not zeroed', 'flag', type),
    field('nVersion', tx.version, 'the transaction’s version, four bytes', 'figure', int(tx.version)),
    field('nLockTime', tx.locktime, 'the earliest the transaction may be mined',
      'locktime', int(tx.locktime)),
    ...(one ? [] : [
      field('sha_prevouts', parts.shaPrevouts, 'every input’s outpoint, hashed once: '
        + 'which coins this transaction spends'),
      field('sha_amounts', parts.shaAmounts, 'every spent coin’s value, hashed — BIP143 signed '
        + 'this input’s own amount; this signs them all'),
      field('sha_scriptpubkeys', parts.shaScriptPubkeys, 'every spent coin’s locking script, hashed'),
      field('sha_sequences', parts.shaSequences, 'every input’s nSequence, hashed'),
    ]),
    ...(parts.shaOutputs != null
      ? [field('sha_outputs', parts.shaOutputs,
        'every output, hashed: the amounts and where they go')]
      : []),
    field('spend_type', le(annex ? 1 : 0, 1), annex
      ? 'an annex rides this input, and the low bit says so; the key path, so no leaf extension'
      : 'zero — the key path, with no annex', 'figure', annex ? 1 : 0),
    ...(one ? [
      field('outpoint', input.txid + input.vout, 'the coin this input spends, named as the chain '
        + 'names it — ANYONECANPAY signs no other input, so any of them may be added or dropped',
        'outpoint', { txid: input.txid, vout: int(input.vout) }),
      field('amount', le(prevout.value, 8), 'what this coin is worth', 'amount', prevout.value),
      field('scriptPubKey', withLength(prevout.script), 'the very lock being opened',
        'script', prevout.script),
      field('nSequence', input.sequence, 'this input’s own sequence',
        'sequence', int(input.sequence)),
    ] : [
      field('input_index', le(nIn, 4),
        'which input of the transaction this signature belongs to', 'figure', nIn),
    ]),
    ...(annex ? [field('sha_annex', parts.shaAnnex, 'the annex this input carries, '
      + 'length-prefixed and hashed')] : []),
    ...(parts.shaSingle != null
      ? [field('sha_output', parts.shaSingle, 'the one output at this input’s index, hashed — '
        + 'SINGLE signs where its own value goes and frees the rest')]
      : []),
  ];
}

// ─── which message, for which spend ──────────────────────────────────────
//
// The algorithm is chosen by the output being opened, not by the transaction
// doing the opening — which is the whole reason a spend rung can name a message
// at all. A v0 program signs under BIP143; everything before it signs under the
// legacy digest; and a P2SH output that wrapped a v0 program signs under BIP143
// too, since what the redeem script revealed is a witness program like any
// other.
//
// Null where the message cannot be named rather than a guess at one: a taproot
// spend that took its script path, and any shape whose scriptCode this cannot
// say. A ⌘ … on the page is the honest form of "not known", and it is better
// than bytes a reader would hash and find wrong.
//
// The script path is declined on two facts, either one sufficient. Its flag
// rides on a signature standing somewhere among the leaf's own arguments, at a
// position only running the script could name; and its extension commits to
// the last OP_CODESEPARATOR executed, which is a fact about execution, not
// bytes. The key path has neither problem — one witness item, and it is the
// signature — and it is also the only alternative whose term writes ⌘ at all:
// the script path's line ends at ( t ), whose demands the output never knew.
const V0_KEYHASH = /^0014([0-9a-f]{40})$/;
const V0_SCRIPTHASH = /^0020[0-9a-f]{64}$/;
const V1_TAPROOT = /^5120[0-9a-f]{64}$/;

// How the digest is taken from the fields, said on the page beside it — two
// hashings now, so the ⌘ row has to say which this message used.
const DSHA_SAID = 'SHA-256 of the SHA-256 of every field above, in the order they are set: '
  + 'the number this signature was made over';
const TAGGED_SAID = 'the TapSighash tagged hash of every field above, in the order they are '
  + 'set — SHA-256 taken once, over the tag’s own hash twice and then the fields: the number '
  + 'this signature was made over';

// The last push of a scriptSig, which is the redeem script a P2SH spend
// revealed. Read off the bytes rather than the term, because the term of the
// OUTPUT is a hash and knows nothing about it.
function lastPush(scriptsig) {
  const b = bytesOf(scriptsig);
  let i = 0, last = null;
  while (i < b.length) {
    const op = b[i++];
    let n = null;
    if (op >= 0x01 && op <= 0x4b) n = op;
    else if (op === 0x4c) n = b[i++];
    else if (op === 0x4d) { n = b[i] | (b[i + 1] << 8); i += 2; }
    else if (op === 0x4e) { n = b[i] | (b[i + 1] << 8) | (b[i + 2] << 16) | (b[i + 3] << 24); i += 4; }
    if (n === null) continue;                       // an opcode, not a push
    if (i + n > b.length) return null;
    last = hex(b.slice(i, i + n));
    i += n;
  }
  return last;
}

export async function messageOf({ script, raw, index, value, items = [], scriptsig = null,
                                  prevouts = null }) {
  let tx;
  try { tx = parseTx(raw); } catch { return null; }
  if (!tx || index >= tx.ins.length) return null;
  const witness = items.length ? items : (tx.ins[index].witness || []);
  // A P2SH output hands its own reading over to what the spend revealed: a
  // wrapped witness program signs as that program, and anything else signs
  // legacy under the redeem script itself.
  let program = String(script).toLowerCase();
  let redeem = null;
  if (/^a914[0-9a-f]{40}87$/.test(program) && scriptsig) {
    redeem = lastPush(scriptsig);
    if (redeem && (V0_KEYHASH.test(redeem) || V0_SCRIPTHASH.test(redeem))) program = redeem;
  }
  // Taproot signs under BIP341, and which path the spend took is consensus's
  // own count: an annex is the last item behind a leading 0x50 and is never an
  // argument, and one item besides it is the key path — that item the
  // signature, its flag the 65th byte or, absent, DEFAULT. The script path is
  // declined, not guessed — see above. `prevouts` is every coin this
  // transaction spends, which BIP341 signs whole and no flag does without.
  if (V1_TAPROOT.test(program)) {
    const annex = witness.length >= 2 && witness[witness.length - 1].startsWith('50')
      ? witness[witness.length - 1] : null;
    const args = annex ? witness.slice(0, -1) : witness;
    if (args.length !== 1) return null;             // the script path, or nothing brought
    const sig = args[0];
    const n = sig.length / 2;
    if (n !== 64 && n !== 65) return null;
    const type = sighashOf(sig);
    if (n === 65 && type === 0x00) return null;     // DEFAULT is said by omission, or not at all
    const preimage = await bip341Preimage(tx, index, prevouts, type, { annex });
    if (!preimage) return null;
    const spent = prevouts.length === tx.ins.length ? prevouts : null;
    const parts = await bip341Parts(tx, index, anyone(type) ? [prevouts[index]] : spent,
      type, annex);
    return { algorithm: 'BIP341', why: 'a taproot output, opened by its key path',
      preimage, type, digest: await taggedHash('TapSighash', preimage), digestSaid: TAGGED_SAID,
      fields: bip341Fields(tx, index, prevouts[index], type, annex, parts) };
  }

  const keyhash = V0_KEYHASH.exec(program);
  if (keyhash || V0_SCRIPTHASH.test(program)) {
    if (value == null) return null;                 // BIP143 signs the amount; without it there is no message
    const sig = witness[0];
    if (!sig) return null;
    const type = sighashOf(sig);
    const code = keyhash ? v0KeyHashCode(keyhash[1]) : witness[witness.length - 1];
    if (!code) return null;
    const preimage = await bip143Preimage(tx, index, code, value, type);
    const parts = await bip143Parts(tx, index, type);
    return { algorithm: 'BIP143', why: 'a version 0 witness program', preimage, type,
      digest: await dsha256(preimage), digestSaid: DSHA_SAID, scriptCode: code,
      fields: bip143Fields(tx, index, code, value, type, parts) };
  }
  // Everything else is the legacy digest, under the output's own script -- or,
  // for a P2SH spend, under the redeem script the input revealed.
  const code = redeem ?? program;
  const sig = witness[0] ?? (scriptsig ? firstPush(scriptsig) : null);
  if (!sig) return null;
  const type = sighashOf(sig);
  const preimage = legacyPreimage(tx, index, code, type);
  if (!preimage) return null;
  return { algorithm: 'legacy', why: 'an output written before segwit', preimage, type,
    digest: await dsha256(preimage), digestSaid: DSHA_SAID, scriptCode: code,
    fields: legacyFields(tx, index, code, type) };
}

// The first push of a scriptSig, which is where a legacy spend puts its
// signature -- P2PKH's s p, P2SH's own arguments, multisig's after its ⓪.
function firstPush(scriptsig) {
  const b = bytesOf(scriptsig);
  if (!b.length) return null;
  const op = b[0];
  if (op < 0x01 || op > 0x4b || 1 + op > b.length) return null;
  return hex(b.slice(1, 1 + op));
}

// The three sub-hashes, kept so the fields can be named without hashing twice.
async function bip143Parts(tx, nIn, type) {
  const zero = '00'.repeat(32);
  const out = (o) => o.value + withLength(o.script);
  return {
    hashPrevouts: anyone(type) ? zero : await dsha256(tx.ins.map((i) => i.txid + i.vout).join('')),
    hashSequence: anyone(type) || base(type) === SIGHASH_SINGLE || base(type) === SIGHASH_NONE
      ? zero : await dsha256(tx.ins.map((i) => i.sequence).join('')),
    hashOutputs: base(type) !== SIGHASH_SINGLE && base(type) !== SIGHASH_NONE
      ? await dsha256(tx.outs.map(out).join(''))
      : base(type) === SIGHASH_SINGLE && nIn < tx.outs.length ? await dsha256(out(tx.outs[nIn])) : zero,
  };
}

// The legacy preimage cut at its joints. It has no fixed shape -- it is the
// whole transaction again -- so the pieces are the transaction's own, and what
// they show is the hole: there is no amount anywhere in this list.
function legacyFields(tx, nIn, code, type) {
  const one = anyone(type);
  const outs = base(type) === SIGHASH_NONE ? 0
    : base(type) === SIGHASH_SINGLE ? nIn + 1 : tx.outs.length;
  return [
    field('nVersion', tx.version, 'the transaction’s version, four bytes', 'figure', int(tx.version)),
    field('inputs', compact(one ? 1 : tx.ins.length), one
      ? 'one — ANYONECANPAY serializes this input alone' : 'how many inputs follow',
      'figure', one ? 1 : tx.ins.length),
    field('scriptCode', withLength(code), 'this input’s script, standing where its scriptSig would; '
      + 'every other input’s is blanked to nothing', 'script', code),
    field('outputs', compact(outs),
      base(type) === SIGHASH_NONE ? 'none — NONE commits to no output at all'
        : base(type) === SIGHASH_SINGLE ? 'up to this input’s index, with every earlier one blanked'
        : 'all of them, amounts and scripts', 'figure', outs),
    field('nLockTime', tx.locktime, 'the earliest the transaction may be mined',
      'locktime', int(tx.locktime)),
    field('nHashType', le(type, 4),
      `${sighashName(type)} — which of the above the signature covers`, 'flag', type),
    field('(no amount)', '', 'the value being spent is nowhere in this serialization — '
      + 'the hole BIP143 closed', 'none'),
  ];
}
